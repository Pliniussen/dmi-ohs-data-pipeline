def add(num_1: int | float, num_2: int | float) -> int | float:
    """Adds two numbers.

    Args:
        num_1 (int | float): The first number.
        num_2 (int | float): The second number.

    Returns:
        int | float: The result of the addition operation.
    """
    return num_1 + num_2

def subtract(num_1: int | float, num_2: int | float) -> int | float:
    """Subtracts a number from another number.

    Args:
        num_1 (int | float): The number that is subtracted from.
        num_2 (int | float): The number that is subtracted.

    Returns:
        int | float: The result of the subtraction operation.
    """
    return num_1 - num_2